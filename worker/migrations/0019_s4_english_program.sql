    's4-eng-y' || w.y || '-w' || printf('%02d', w.wk) || '-l' || l.n AS k
  FROM w
  JOIN u ON u.y = w.y AND w.wk BETWEEN u.wf AND u.wt
  CROSS JOIN l
)
