x AS (
  SELECT
    w.y AS y, w.wk AS wk, u.n AS un, (w.wk - u.wf + 1) AS uw, (u.wt - u.wf + 1) AS uweeks,
    u.unit AS unit, u.strand AS strand, l.n AS ln,
    CASE l.n WHEN 1 THEN w.t1 WHEN 2 THEN w.t2 ELSE w.t3 END AS tt,
    's4-tech-y' || w.y || '-w' || printf('%02d', w.wk) || '-l' || l.n AS k
  FROM w
  JOIN u ON u.y = w.y AND w.wk BETWEEN u.wf AND u.wt
  CROSS JOIN l
)
INSERT OR IGNORE INTO lessons (id, family_id, seed_key, title, stage, learning_area, unit_id, status, data, created_at, updated_at)
