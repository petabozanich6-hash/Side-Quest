// Builds worker/src/data/ac9-outcomes.ts from ACARA's official machine-readable Australian Curriculum v9 (MRAC).
// Source: https://www.australiancurriculum.edu.au/machine-readable-australian-curriculum (CC BY 4.0, © ACARA).
// Run: node worker/scripts/import-ac9.mjs   (needs open internet; the "Import AC9 curriculum" GitHub workflow runs it)
// Languages are skipped (they are per-language and very large). Only content descriptions are kept; elaborations are
// not used for alignment, as ACARA advises.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { ac9Level } from "./ac9-code-level.mjs";

const RELEASE = "MRAC/2024/04";
const AREAS = {
  ENG: "English", MAT: "Mathematics", SCI: "Science", HASS: "Humanities and Social Sciences",
  HPE: "Health and Physical Education", ART: "The Arts", TEC: "Technologies",
  LAN: "Languages",
};
const BANDED = new Set(["ART", "HPE", "TEC", "LAN"]); // Includes Languages F–10 and 7–10 bands; retain pathway metadata

const P = "http://purl.org/ASN/schema/core/", D = "http://purl.org/dc/terms/", Q = "http://purl.org/gem/qualifiers/";
const val = (x, k) => (x?.[k] || [])[0]?.["@value"] || "";
const clean = (s) => s.replace(/<[^>]+>/g, "").replace(/\\\((.*?)\\\)/g, "$1").replace(/\s+/g, " ").trim();

async function extract(la) {
  const url = `https://vocabulary.curriculum.edu.au/${RELEASE}/LA/${la}/export/${RELEASE}/LA/${la}.jsonld`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${la}: HTTP ${res.status}`);
  const data = JSON.parse(await res.text());
  const graph = (Array.isArray(data) ? data[0] : data)["@graph"];
  const byId = new Map(graph.map((x) => [x["@id"], x]));
  const label = (x) => val(x, P + "statementLabel");
  const parent = (x) => byId.get((x?.[Q + "isChildOf"] || [])[0]?.["@id"]);
  const out = [];
  for (const x of graph) {
    if (label(x) !== "Content Description") continue;
    const code = val(x, P + "statementNotation").trim();
    const n = ac9Level(code);
    if (n === null) throw new Error(`Invalid or unparseable official AC9 level: ${la} ${code}`);
    const from = BANDED.has(la) && n > 0 ? n - 1 : n;
    let strand = "", subject = "", pathway = "", p = parent(x), guard = 0;
    while (p && guard++ < 12) {
      const l = label(p), t = clean(val(p, D + "title"));
      if (l === "Strand" || l === "Sub-Strand") strand = strand ? `${t} > ${strand}` : t;
      if (l === "Subject") subject = t;
      if (la === "LAN" && /^(?:Pathway|Sequence|Learning Sequence)$/i.test(l) && t) pathway = pathway ? t + " > " + pathway : t;
      p = parent(p);
    }
    const description = clean(val(x, D + "description"));
    if (!description) continue;
    out.push({ code, learning_area: AREAS[la], subject: subject || AREAS[la], strand, pathway, from, to: n, description });
  }
  return out;
}

const all = [];
for (const la of Object.keys(AREAS)) {
  const rows = await extract(la);
  console.log(`${la}: ${rows.length}`);
  all.push(...rows);
}
all.sort((a, b) => a.code.localeCompare(b.code));
if (all.length < 1000) throw new Error(`Only ${all.length} content descriptions found; refusing to write a partial list.`);
const seen = new Set();
for (const row of all) {
  if (!/^(?:AC9|ACL9)[A-Z0-9]+$/.test(row.code) || seen.has(row.code)) throw new Error(`Duplicate/invalid official identifier: ${row.code}`);
  seen.add(row.code);
}
// Fail instead of silently omitting any whole learning area (especially Languages).
for (const [abbr, name] of Object.entries(AREAS)) {
  const count = all.filter(row => row.learning_area === name).length;
  if (count < (abbr === "LAN" ? 100 : 1)) throw new Error(`Incomplete AC9 ${name} import: ${count} content descriptions`);
}

const header = `// GENERATED by worker/scripts/import-ac9.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
// Australian Curriculum Version 9.0 content descriptions (${RELEASE}), including Languages and language pathways.
// © Australian Curriculum, Assessment and Reporting Authority (ACARA) 2010 to present, unless otherwise indicated.
// Downloaded from the Australian Curriculum website (https://www.australiancurriculum.edu.au/machine-readable-australian-curriculum)
// and used under CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/). Reformatted into a list; wording unchanged
// apart from removing HTML/LaTeX markup. ACARA does not endorse Side-Quest.
// from/to = year levels the description applies to (0 = Foundation). Banded subjects cover two years.
export type Ac9Outcome = { code: string; learning_area: string; subject: string; strand: string; pathway?: string; from: number; to: number; description: string };
export const AC9_SOURCE = "Australian Curriculum v9.0 (ACARA, CC BY 4.0)";
export const AC9_OUTCOMES: Ac9Outcome[] = `;
const target = fileURLToPath(new URL("../src/data/ac9-outcomes.ts", import.meta.url));
writeFileSync(target, header + JSON.stringify(all, null, 0).replace(/\},\{/g, "},\n{") + ";\n");
console.log(`Wrote ${all.length} content descriptions to ${target}`);
