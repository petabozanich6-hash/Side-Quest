// Builds worker/src/data/vic-source-ids.ts from the Victorian Curriculum v2.0 codes that already have a Side-Quest
// summary in outcome-summaries.json. Codes and structure only: no VCAA wording is stored (the Victorian Curriculum
// is CC BY-NC; the official wording stays on f10.vcaa.vic.edu.au and is linked from every outcome).
// Structure comes from the official code pattern: VC2 + subject + level + strand + number, e.g. VC2M3N01, VC2HH8K02.
// Maths and English have a code for every level (F, 1..10). Other subjects use two-year bands named by their upper
// level (2, 4, 6, 8, 10); where a subject has no separate Foundation code, its "2" band covers Foundation to Level 2.
// Run: node worker/scripts/build-vic-codes.mjs
import { readFileSync, writeFileSync } from "node:fs";

const summaries = JSON.parse(readFileSync(new URL("../src/data/outcome-summaries.json", import.meta.url), "utf8"));
const SUBJECTS = {
  M: ["Mathematics", "Mathematics"], E: ["English", "English"], S: ["Science", "Science"],
  HH: ["Humanities and Social Sciences", "History"], HG: ["Humanities and Social Sciences", "Geography"],
  HC: ["Humanities and Social Sciences", "Civics and Citizenship"], HE: ["Humanities and Social Sciences", "Economics and Business"],
  HP: ["Health and Physical Education", "Health and Physical Education"],
  ADA: ["The Arts", "Dance"], ADR: ["The Arts", "Drama"], AMA: ["The Arts", "Media Arts"], AMU: ["The Arts", "Music"],
  AVA: ["The Arts", "Visual Arts"], AVC: ["The Arts", "Visual Communication Design"],
  TDE: ["Technologies", "Design and Technologies"], TDI: ["Technologies", "Digital Technologies"],
  CC: ["Critical and Creative Thinking", "Critical and Creative Thinking"], CE: ["Ethical Capability", "Ethical Capability"],
  CI: ["Intercultural Capability", "Intercultural Capability"], CP: ["Personal and Social Capability", "Personal and Social Capability"],
};
const LANGS = { LA: "Arabic", LC: "Chinese", LF: "French", LG: "German", LH: "Hindi", LIN: "Indonesian", LIT: "Italian", LJ: "Japanese",
  LK: "Korean", LMG: "Modern Greek", LS: "Spanish", LT: "Turkish", LV: "Vietnamese", LL: "Latin", LCG: "Classical Greek" };
const URL_F10 = "https://f10.vcaa.vic.edu.au/";
const stageOf = (y) => (y === 0 ? "ES1" : "S" + Math.ceil(y / 2));

const codes = Object.keys(summaries).filter((c) => /^VC2/.test(c));
const parsed = codes.map((c) => ({ c, m: /^VC2([A-Z]+?)(F|10|[1-9])([A-Z]+)(\d{2})$/.exec(c) })).filter((x) => x.m);
const hasF = new Set(parsed.filter((x) => x.m[2] === "F").map((x) => x.m[1]));
// Pre-Foundation levels A-D (students with disability) put a level letter before the strand, e.g. VC2MFAN01, VC2MFCSP02.
// A Foundation strand that isn't a real strand of that subject at Level 1 or 2, but is one after its first letter, is pre-Foundation.
const strandsAbove = new Map();
for (const { m } of parsed) if (m[2] === "1" || m[2] === "2") { const set = strandsAbove.get(m[1]) || new Set(); set.add(m[3]); strandsAbove.set(m[1], set); }
const preFoundation = (subj, strand) => {
  const real = strandsAbove.get(subj);
  return !!real && !real.has(strand) && /^[ABCD]/.test(strand) && real.has(strand.slice(1));
};
const everyLevel = new Set(["M", "E"]);
const rows = [];
for (const { c, m } of parsed) {
  const [, subj, lvl, strand] = m;
  if (lvl === "F" && preFoundation(subj, strand)) continue;
  let area, subject, pathway;
  if (SUBJECTS[subj]) [area, subject] = SUBJECTS[subj];
  else if (LANGS[subj]) { area = "Languages"; subject = LANGS[subj]; pathway = subject; }
  else continue; // pre-Foundation levels and unrecognised subjects are left out rather than guessed
  let from, to;
  if (lvl === "F") { from = 0; to = 0; }
  else {
    const n = Number(lvl);
    if (everyLevel.has(subj)) { from = n; to = n; }
    else { to = n; from = n === 2 && !hasF.has(subj) ? 0 : n - 1; }
  }
  const levels = [];
  for (let y = from; y <= to; y++) levels.push(y === 0 ? "Foundation" : String(y));
  rows.push({ code: c, learning_area: area, subject, ...(pathway ? { pathway } : {}), stage: stageOf(to), levels, from, to,
    source: "VCAA Victorian Curriculum F–10 v2.0 (codes only)", source_url: URL_F10 });
}
rows.sort((a, b) => a.code.localeCompare(b.code));
const out = `// GENERATED by worker/scripts/build-vic-codes.mjs from the Victorian Curriculum F–10 v2.0 codes that have a
// Side-Quest summary (outcome-summaries.json). Codes and structure ONLY: no VCAA wording is stored. The Victorian
// Curriculum is © VCAA, licensed CC BY-NC; official wording: https://f10.vcaa.vic.edu.au/
export type VicSourceRecord = { code:string; learning_area:string; stage?:string; source:string; subject?:string; learning_areas?:string[]; subjects?:string[]; pathway?:string; pathways?:string[]; levels?:string[]; status?:string; source_url:string; from?:number; to?:number };
export const VIC_SOURCE_VERIFIED_IDS: VicSourceRecord[] = [
${rows.map((r) => JSON.stringify(r)).join(",\n")}
];
`;
writeFileSync(new URL("../src/data/vic-source-ids.ts", import.meta.url), out);
console.log(`${rows.length} Victorian codes written (${codes.length - rows.length} left out).`);
